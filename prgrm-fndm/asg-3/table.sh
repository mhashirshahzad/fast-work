#!/usr/bin/env bash

CY='\033[96m'; YE='\033[93m'; GR='\033[92m'; RD='\033[91m'
MA='\033[95m'; BL='\033[94m'; WH='\033[97m'; DM='\033[2m'
BO='\033[1m'; RS='\033[0m'

echo -e "${BO}${CY}┌────────────────────────────────────────────────────────────────────────────────────┐${RS}"
echo -e "${CY}│${RS} ${BO}${YE}   n   ${RS} ${CY}│${RS} ${BO}${YE}     digits    ${RS} ${CY}│${RS} ${BO}${YE}   new N   ${RS} ${CY}│${RS} ${BO}${YE}    prev Numbers    ${RS} ${CY}│${RS} ${BO}${YE} Did Appear before ${RS} ${CY}│${RS}"
echo -e "${CY}│─────────│─────────────────│─────────────│──────────────────────│───────────────────│${RS}"

row() {
  local n="$1" digits="$2" newn="$3" prev="$4" app="$5"
  local ac
  if [ "$app" = "Yes" ]; then ac="${BO}${RD}"; else ac="${BO}${GR}"; fi
  echo -e "${CY}│${RS} ${BO}${WH}   $n   ${RS} ${CY}│${RS} ${BL}  $digits  ${RS} ${CY}│${RS} ${BO}${MA}    $newn    ${RS} ${CY}│${RS} ${DM} $prev ${RS} ${CY}│${RS} ${ac}        $app        ${RS} ${CY}│${RS}"
}

row "4"   "4^2"             "16"  "4"                    "No"
row "16"  "1^2 + 6^2"       "37"  "4 16"                 "No"
row "37"  "3^2 + 7^2"       "58"  "4 16 37"              "No"
row "58"  "5^2 + 8^2"       "89"  "4 16 37 58"           "No"
row "89"  "8^2 + 9^2"       "145" "4 16 37 58 89"        "No"
row "145" "1^2 + 4^2 + 5^2" "42"  "4 16 37 58 89 145"    "No"
row "42"  "4^2 + 2^2"       "20"  "4 16 37 58 89 145 20" "No"
row "20"  "2^2 + 0^2"       "4"   "4 16 37 58 89 145 20" "Yes"

echo -e "${CY}└────────────────────────────────────────────────────────────────────────────────────┘${RS}"
